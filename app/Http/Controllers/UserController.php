<?php

namespace App\Http\Controllers;

use App\Actions\Users\ApproveUser;
use App\Actions\Users\CreateUser;
use App\Actions\Users\DeactivateUser;
use App\Actions\Users\DeleteUser;
use App\Actions\Users\GenerateTemporaryPassword;
use App\Http\Requests\ApproveUserRequest;
use App\Http\Requests\StoreUserRequest;
use App\Http\Resources\UserResource;
use App\Models\Team;
use App\Models\User;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\Request;
use Illuminate\Http\Resources\Json\AnonymousResourceCollection;
use Symfony\Component\HttpFoundation\Response;

class UserController extends Controller
{
    /**
     * List accounts, optionally filtered by status or role.
     */
    public function index(Request $request): AnonymousResourceCollection
    {
        $users = User::query()
            ->with('team')
            ->when(
                $request->filled('status'),
                fn ($query) => $query->where('status', $request->string('status')->toString()),
            )
            ->when(
                $request->filled('role'),
                fn ($query) => $query->where('role', $request->string('role')->toString()),
            )
            ->orderBy('name')
            ->paginate(20);

        return UserResource::collection($users);
    }

    /**
     * Create an active account on behalf of an admin. The temporary password is
     * generated by the backend and returned exactly once, in this response.
     */
    public function store(
        StoreUserRequest $request,
        CreateUser $createUser,
        GenerateTemporaryPassword $generateTemporaryPassword,
    ): JsonResponse {
        $temporaryPassword = $generateTemporaryPassword->handle();

        $user = $createUser->handle($request->user(), $request->validated(), $temporaryPassword);

        return (new UserResource($user->load('team')))
            ->additional([
                'temporary_password' => $temporaryPassword,
            ])
            ->response()
            ->setStatusCode(Response::HTTP_CREATED);
    }

    /**
     * Show a single account.
     */
    public function show(User $user): UserResource
    {
        return new UserResource($user->loadMissing('team'));
    }

    /**
     * Approve a pending account and assign it to a team.
     */
    public function approve(ApproveUserRequest $request, User $user, ApproveUser $approveUser): UserResource
    {
        $user = $approveUser->handle(
            $user,
            Team::findOrFail($request->validated('team_id')),
            $request->user(),
        );

        return new UserResource($user->load('team'));
    }

    /**
     * Deactivate an account.
     */
    public function deactivate(User $user, DeactivateUser $deactivateUser): UserResource
    {
        return new UserResource($deactivateUser->handle($user)->load('team'));
    }

    /**
     * Soft delete an account.
     */
    public function destroy(User $user, DeleteUser $deleteUser): Response
    {
        $deleteUser->handle($user);

        return response()->noContent();
    }
}
