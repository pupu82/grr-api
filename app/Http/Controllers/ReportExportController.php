<?php

namespace App\Http\Controllers;

use App\Actions\Exports\CreateSessionEvaluationExport;
use App\Enums\ExportFormat;
use App\Enums\ExportStatus;
use App\Http\Requests\StoreSessionExportRequest;
use App\Http\Resources\ReportExportResource;
use App\Models\InspectionSession;
use App\Models\ReportExport;
use Illuminate\Http\JsonResponse;
use Illuminate\Support\Facades\Storage;
use Illuminate\Validation\ValidationException;
use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpFoundation\StreamedResponse;

class ReportExportController extends Controller
{
    /**
     * Queue the evaluation export. The file is generated by a job so a large
     * session never blocks the request.
     */
    public function store(
        StoreSessionExportRequest $request,
        InspectionSession $session,
        CreateSessionEvaluationExport $createExport,
    ): JsonResponse {
        $export = $createExport->handle(
            $request->user(),
            $session,
            ExportFormat::from($request->validated('format')),
        );

        return (new ReportExportResource($export))
            ->response()
            ->setStatusCode(Response::HTTP_ACCEPTED);
    }

    /**
     * Poll the lifecycle of one queued export.
     */
    public function show(ReportExport $export): ReportExportResource
    {
        return new ReportExportResource($export->loadMissing('session'));
    }

    /**
     * Download a completed export from its configured disk.
     */
    public function download(ReportExport $export): StreamedResponse
    {
        $this->assertReady($export);

        $disk = Storage::disk(config('grr.exports.disk'));

        if (! $disk->exists($export->file_path)) {
            throw ValidationException::withMessages([
                'export' => 'The report file is no longer available.',
            ]);
        }

        $headers = $export->format === ExportFormat::Csv
            ? ['Content-Type' => 'text/csv']
            : [];

        return $disk->download($export->file_path, $export->file_name, $headers);
    }

    private function assertReady(ReportExport $export): void
    {
        if ($export->status !== ExportStatus::Completed || ! filled($export->file_path)) {
            throw ValidationException::withMessages([
                'export' => 'The report is not ready for download.',
            ]);
        }
    }
}
